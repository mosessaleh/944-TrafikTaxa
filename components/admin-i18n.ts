function getByPath(source: any, path: string): any {
  return path.split('.').reduce((value, key) => value?.[key], source);
}

export function useAdminTranslations() {
  const [language, setLanguage] = useState<Locale>('dk');

  useEffect(() => {
    const readLanguage = () => {
      const saved = localStorage.getItem('language') as Locale | null;
      setLanguage(saved && saved in dictionaries ? saved : 'dk');
    };

    readLanguage();
    const onStorage = (event: StorageEvent) => {
      if (event.key === 'language') readLanguage();
    };
    const onCustom = () => readLanguage();

    window.addEventListener('storage', onStorage);
    window.addEventListener('languageChange' as any, onCustom);
    return () => {
      window.removeEventListener('storage', onStorage);
      window.removeEventListener('languageChange' as any, onCustom);
    };
  }, []);

  function t(path: string, fallback?: string): string {
    const value = getByPath(dictionaries[language], path) ?? getByPath(dictionaries.en, path);
    return typeof value === 'string' ? value : fallback || path;
  }

  function tuple(path: string): [string, string, string] {
    const value = getByPath(dictionaries[language], path) ?? getByPath(dictionaries.en, path);
    return Array.isArray(value) ? value as [string, string, string] : ['', '', ''];
  }

  return { t, tuple, language };
}
